import { expect, it, vi } from 'vitest';
vi.mock('~/lib/socket-sender', () => ({ sendEventAsync: vi.fn() }));
vi.mock('~/lib/indexeddb', () => ({ valtioCache: { get: vi.fn(), set: vi.fn(), delete: vi.fn() } }));
import { BizzaboNode } from '~/components/workflow/nodes/integrations/bizzabo';
import { NODE_SCHEMAS, loadAllNodeSchemas, getNodeCredentialInfo } from '~/utils/nodeSchemas';
import { CREDENTIAL_TYPE_MAP } from '~/utils/credentialTypeMap';
import { credentialRequirements, methodFromRequirement } from '~/components/credential/credentialMethods';
await loadAllNodeSchemas();
it('discovers the native account credential without requiring an OAuth connect flow', () => {
    expect(BizzaboNode.type).toBe('automation-bizzabo');
    expect(CREDENTIAL_TYPE_MAP.BizzaboClientCredentialsCredential).toBe('bizzabo_client_credentials');
    expect(getNodeCredentialInfo(BizzaboNode.type)).toEqual({ providerKey: 'bizzabo', acceptedTypes: ['bizzabo_client_credentials'], label: 'Bizzabo Account' });
    expect(credentialRequirements(BizzaboNode.type).map(req => methodFromRequirement(req).method_kind)).toEqual(['api_key']);
    const schema: any = NODE_SCHEMAS[BizzaboNode.type];
    const credential = schema.$defs.BizzaboClientCredentialsCredential;
    expect(credential['x-oauth-provider']).toBeUndefined();
    expect(credential.properties.client_secret['ui:widget']).toBe('password');
    expect(credential.properties.client_secret['ui:sensitive']).toBe(true);
    expect(credential.properties.access_token).toBeUndefined();
    const contact: any = Object.values(schema.$defs).find((def: any) => def.properties?.operation?.const === 'get_event_contact');
    expect(contact.properties.contact_id['x-dynamic-options'].depends_on).toEqual(['event_id']);
    expect(contact.required).toEqual(expect.arrayContaining(['event_id', 'contact_id']));
});
