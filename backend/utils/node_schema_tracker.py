async def track_node_schema(
    node_type: str,
    node_operation: str,
    output: Any,
    *,
    delivered: bool = False,
    workflow_id: Optional[str] = None,
) -> None:
    """Record a node's output schema, then write its ``suggested_refs`` while
    they're still NULL on the row. Only the schema is kept: ``output``'s
    values are never stored, nor shown to the model that writes the refs.

    Write rule: fill a NULL ``suggested_refs``, leave populated ones alone.
    The runtime tracker never overwrites refs; the backfill script does.

    ``delivered``: ``output`` is a trigger's delivery as it arrived, never
    what a node made of it.

    ``workflow_id``: the workflow it came from, whose owner keeps the shape as
    their own.

    Awaits the upsert + (when needed) the LLM call. All exceptions are
    swallowed; schema tracking must never break workflow execution.
    """
    try:
        schema = extract_schema(output)
        schema_hash = compute_schema_hash(node_type, node_operation, schema)
        pool = get_native_pool()

        upsert_query = """
            INSERT INTO workflow_node_output_schemas (
                node_type, node_operation, output_schema, schema_hash, taught_by
            ) VALUES ($1, $2, $3, $4, $5)
            ON CONFLICT (schema_hash) DO UPDATE SET
                last_seen_at = NOW(),
                occurrence_count = workflow_node_output_schemas.occurrence_count + 1,
                taught_by = CASE WHEN workflow_node_output_schemas.taught_by = 'delivery'
                                 THEN 'delivery' ELSE EXCLUDED.taught_by END
            RETURNING suggested_refs
        """
        # Pass raw Python objects for jsonb params — the asyncpg jsonb codec
        # (setup_asyncpg_codecs) already json.dumps() them on the way in.
        # Pre-serializing here would double-encode, storing a JSON string
        # scalar that reads back as a str instead of a dict/list.
        rows = await pool.fetch(
            upsert_query,
            node_type, node_operation, schema, schema_hash,
            "delivery" if delivered else "run",
        )
        if workflow_id:
            try:
                await node_output_schemas.record(
                    pool, workflow_id=workflow_id, node_type=node_type, node_operation=node_operation,
                    schema=schema, schema_hash=schema_hash, delivered=delivered,
                )
            except Exception as e:  # the account's record never stops the pooled row's refs below
                logger.warning(f"[SchemaTracker] Failed to record {node_type}:{node_operation} for its account: {e}")
        row = rows[0] if rows else None
        if row is not None and row["suggested_refs"] is not None:
            return

        suggested_refs = await _generate_suggested_refs(node_type, node_operation, schema)
        if suggested_refs is None:
            return  # the model failed; the next observation retries

        # COALESCE-guarded: a racing worker's refs win, never overwritten.
        await pool.execute(
            """
            UPDATE workflow_node_output_schemas
            SET suggested_refs = COALESCE(suggested_refs, $1::jsonb),
                suggestions_updated_at = CASE
                    WHEN suggested_refs IS NULL THEN NOW()
                    ELSE suggestions_updated_at
                END
            WHERE schema_hash = $2
            """,
            suggested_refs,
            schema_hash,
        )
    except asyncio.CancelledError:
        raise
    except Exception as e:
        logger.warning(
            f"[SchemaTracker] Failed to track schema for {node_type}:{node_operation}: {e}"
        )


def _served(node_type: str, node_operation: str) -> str:
    """The condition on what a read of (type, operation) may see: see ``taught_by`` above."""
    from nodes.agent.node_op_tools import is_trigger

    return "AND taught_by IS NOT NULL" if is_trigger(node_type, node_operation) else ""


async def get_schema_for_node(node_type: str, node_operation: str) -> Optional[Dict[str, Any]]:
    """Most-common schema for a (type, operation) over every account, or None. For NoClick's own models."""
    try:
        return await get_native_pool().fetchval(
            f"""
            SELECT output_schema
            FROM workflow_node_output_schemas
            WHERE node_type = $1 AND node_operation = $2 {_served(node_type, node_operation)}
            ORDER BY occurrence_count DESC
            LIMIT 1
            """,
            node_type, node_operation,
        )
    except Exception as e:
        logger.warning(f"[SchemaTracker] Failed to get schema for {node_type}:{node_operation}: {e}")
        return None


async def get_schema_with_suggestions(
    node_type: str,
    node_operation: str,
) -> Optional[Dict[str, Any]]:
    """Most-common schema row over every account, with its curated suggestions.
    For NoClick's own models.

    Returns ``{"schema": ..., "suggested_refs": ... | None}`` or ``None``
    if no row exists yet. ``suggested_refs`` is None while the LLM hasn't
    produced a valid result yet (loading state on the frontend).
    """
    try:
        rows = await get_native_pool().fetch(
            f"""
            SELECT output_schema, suggested_refs
            FROM workflow_node_output_schemas
            WHERE node_type = $1 AND node_operation = $2 {_served(node_type, node_operation)}
            ORDER BY occurrence_count DESC
            LIMIT 1
            """,
            node_type, node_operation,
        )
        if not rows:
            return None
        row = rows[0]
        return {
            "schema": row["output_schema"],
            "suggested_refs": row["suggested_refs"],
        }
    except Exception as e:
        logger.warning(
            f"[SchemaTracker] Failed to get schema+suggestions for {node_type}:{node_operation}: {e}"
        )
        return None


async def get_own_schema_with_suggestions(
    user_id: str,
    node_type: str,
    node_operation: str,
) -> Optional[Dict[str, Any]]:
    """As ``get_schema_with_suggestions``, of what this account and its workspaces' members have seen alone:
    ``None`` until one of them has."""
    try:
        row = await node_output_schemas.most_seen(get_native_pool(), user_id, node_type, node_operation)
        return row and {"schema": row["output_schema"], "suggested_refs": row["suggested_refs"]}
    except Exception as e:
        logger.warning(f"[SchemaTracker] Failed to get own schema for {node_type}:{node_operation}: {e}")
        return None


async def get_all_schemas_for_node(node_type: str, node_operation: str) -> list:
    """All known schemas for a (type, operation), ordered by occurrence count."""
    try:
        rows = await get_native_pool().fetch(
            f"""
            SELECT output_schema, occurrence_count, first_seen_at, last_seen_at,
                   suggested_refs, suggestions_updated_at
            FROM workflow_node_output_schemas
            WHERE node_type = $1 AND node_operation = $2 {_served(node_type, node_operation)}
            ORDER BY occurrence_count DESC
            """,
            node_type, node_operation,
        )
        return [dict(row) for row in rows]
    except Exception as e:
        logger.warning(f"[SchemaTracker] Failed to get schemas for {node_type}:{node_operation}: {e}")
        return []
