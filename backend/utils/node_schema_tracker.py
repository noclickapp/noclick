"""
Node output schema tracking + LLM-curated reference suggestions.

One storage table (``workflow_node_output_schemas``), one rule for the
runtime tracker: **fill what is NULL on the row, leave what's populated
alone.** Concretely:

* The output payload becomes a type-descriptor tree (e.g.
  ``{"name": "John"} → {"name": "string"}``) and the row is upserted by
  ``SHA256(node_type, node_operation, schema)`` — equivalent shapes
  dedup globally.
* No output's values are kept, and none reach a model: every account reads
  this table. ``sample_output_clipped`` and ``sample_config`` are no longer
  written (columns left until no old container writes them).
* ``suggested_refs`` is generated by an LLM (gpt-oss-120b via Groq /
  Cerebras through OpenRouter) from the shape's field names and types alone,
  only when that column is currently NULL. A self-hosted installation also
  needs a non-empty ``OPENROUTER_API_KEY``; without one this optional
  enrichment is skipped without making a request. Once set the runtime never
  overwrites; ``scripts/backfill_suggested_refs.py --all`` rewrites them.
* ``taught_by`` says what the shape came from: ``delivery``, a trigger's
  delivery as it arrived, which is all a public shape may show; or ``run``,
  a node's output. NULL on a row from before it was recorded. A trigger's
  such row isn't read (``_served``): most triggers' manual runs copied the
  run's other outputs into theirs, so it may hold another account's step
  names. A row that's taught again says so; one like that never is.
* Every account's outputs pool in this table and it names none of them, while
  a shape can hold one account's own field names (a webhook's body, a CRM's
  custom properties, a sheet's columns). So its reads are for NoClick's own
  models; what a person or a client outside NoClick reads is the account's own
  record of what it has seen (``repositories/node_output_schemas.py``: written
  with ``workflow_id``, read by ``get_own_schema_with_suggestions``).

The LLM call is awaited inline. Cost is bounded by global dedup: only
the first observation of a given shape pays for the LLM, and a row that
already has its references is a single upsert.
"""

import asyncio
import hashlib
import json
import logging
import os
import re
from typing import Any, Dict, List, Optional

import litellm

from repositories import node_output_schemas
