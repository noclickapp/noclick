def _snake(name: str) -> str:
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def _title(name: str) -> str:
    return _snake(name).replace("_", " ").title()


def _make_config(key: str, operation: dict[str, Any]) -> type[BaseModel]:
    metadata = {
        "const": key,
        "ui:hidden": True,
        "x-display-name": operation["label"],
        "x-category": operation["category"],
        "x-is-trigger": False,
    }
    if operation["method"] == "POST" and any(
        verb in key for verb in ("create", "upsert", "update_user")
    ):
        metadata["x-creates-resource"] = True
        metadata["x-resource-type"] = "iterable_" + key
    fields: dict[str, tuple[Any, Any]] = {
        "operation": (Literal[key], Field(key, title=operation["label"], json_schema_extra=metadata))
    }
    for parameter in re.findall(r"\{([^}]+)\}", operation["path"]):
        fields[parameter] = (str, Field(..., title=_title(parameter), min_length=1))
    for parameter in operation["required_query_params"]:
        fields["query_" + _snake(parameter)] = (
            str, Field(..., title=_title(parameter), min_length=1)
        )
    optional_query = set(operation["query_params"]) - set(operation["required_query_params"])
    if optional_query:
        fields["query_json"] = (
            Optional[str], Field(
                None, title="Other Query Parameters JSON",
                description="Optional Iterable query keys: " + ", ".join(sorted(optional_query)),
                json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
            )
        )
    if operation["has_body"]:
        required = operation["body_fields"]
        hint = "Required keys: " + ", ".join(required) if required else "Use Iterable's request body schema."
        fields["payload_json"] = (
            str if operation["body_required"] else Optional[str],
            Field(
                ... if operation["body_required"] else None,
                title="Request JSON", description=hint,
                json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
            ),
        )
    return create_model(
        "Iterable" + "".join(part.title() for part in key.split("_")) + "Config",
        __module__=__name__, **fields,
    )


CONFIG_MODELS = {key: _make_config(key, operation) for key, operation in OPERATIONS.items()}
globals().update({model.__name__: model for model in CONFIG_MODELS.values()})
IterableConfig = Annotated[Union[tuple(CONFIG_MODELS.values())], Discriminator("operation")]


class IterableNodeConfig(NodeConfig[IterableConfig, IterableApiKeyCredential]):
    model_config = ConfigDict(json_schema_extra={"x-agent-tool-provider": True})


def _json_object(value: str, label: str) -> dict[str, Any]:
    try:
        parsed = json.loads(value)
    except (TypeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} must be valid JSON") from exc
    if not isinstance(parsed, dict):
        raise ValueError(f"{label} must be a JSON object")
    return parsed


class IterableNode(WorkflowNode):
    integration_type = "automation-iterable"
    connection_evidence = ConnectionEvidence(operation="list_lists", noun="lists")
    edit_examples = [
        "Get Iterable lists and campaign performance",
        "Add a user to an Iterable list",
        "Update an Iterable user profile and track an event",
        "Create an Iterable campaign from a template",
    ]

    @classmethod
    def get_config_model(cls):
        return IterableNodeConfig

    @staticmethod
    async def _request(
        credential: IterableApiKeyCredential, method: str, path: str,
        *, params: dict[str, Any] | None = None, body: dict[str, Any] | None = None,
    ) -> Any:
        url = BASE_URLS[credential.region] + path
        async with guarded_async_client(timeout=45.0) as client:
            response = await client.request(
                method, url, params=params, json=body,
                headers={"Api-Key": credential.api_key, "Accept": "application/json"},
            )
        if not response.content:
            data: Any = {"ok": True}
        else:
            try:
                data = response.json()
            except ValueError:
                data = {"text": response.text}
        if response.is_error:
            detail = (
                data.get("msg") or data.get("message") or data.get("error")
                if isinstance(data, dict) else None
            )
            raise ValueError(f"Iterable API error {response.status_code}: {detail or 'request failed'}")
        return data

    async def execute(self, inputs: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(self.config, IterableNodeConfig):
            raise ValueError("Iterable configuration required")
        credential = self.config.credentials
        if credential is None:
            raise ValueError("Connect an Iterable server-side API key")
        config = self.config.config
        operation = OPERATIONS[config.operation]
        values = config.model_dump(exclude_none=True, exclude={"operation"})
        path = operation["path"]
        for parameter in re.findall(r"\{([^}]+)\}", path):
            path = path.replace("{" + parameter + "}", quote(str(values.pop(parameter)), safe=""))
        params = _json_object(values.pop("query_json"), "Query Parameters JSON") if "query_json" in values else {}
        for parameter in operation["required_query_params"]:
            params[parameter] = values.pop("query_" + _snake(parameter))
        body = _json_object(values.pop("payload_json"), "Request JSON") if "payload_json" in values else None
        data = await self._request(credential, operation["method"], path, params=params or None, body=body)
        return {"status": "success", "operation": config.operation, "data": data}
