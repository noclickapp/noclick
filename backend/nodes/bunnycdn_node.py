def _parse_json(value: Optional[str], field: str, *, object_only: bool = False) -> Any:
    if value is None or value == "":
        return None
    try:
        parsed = json.loads(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Bunny.net {field} must be valid JSON") from exc
    if object_only and not isinstance(parsed, dict):
        raise ValueError(f"Bunny.net {field} must be a JSON object")
    if not object_only and not isinstance(parsed, (dict, list)):
        raise ValueError(f"Bunny.net {field} must be a JSON object or array")
    return parsed


def _event_log_date(value: str) -> str:
    """Normalize calendar inputs to the provider's documented path format."""
    try:
        parsed = datetime.strptime(value, "%m-%d-%Y")
    except ValueError:
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError as exc:
            raise ValueError(
                "Bunny.net event log date must be a valid MM-dd-yyyy date, ISO date, or ISO timestamp"
            ) from exc
    return parsed.strftime("%m-%d-%Y")


class BunnyNode(WorkflowNode):
    """Execute a JSON-oriented Bunny.net API action."""

    integration_type = "automation-bunnycdn"
    credential_provider_labels = {"bunnycdn": "Bunny.net"}

    edit_examples = [
        "List my Bunny.net pull zones",
        "Purge a CDN URL",
        "List recent Bunny Shield event logs",
        "Create a Bunny Stream video collection",
    ]
    connection_evidence = ConnectionEvidence(
        operation="list_connection_resources", noun="resources"
    )

    @classmethod
    def get_config_model(cls):
        return BunnyNodeConfig

    async def execute(self, inputs: Dict[str, Any]) -> Dict[str, Any]:
        started = time.monotonic()
        if not isinstance(self.config, BunnyNodeConfig):
            raise ValueError("Bunny.net configuration is required")
        credential = self.config.credentials
        if not credential:
            raise ValueError("Bunny.net API key credential is required")
        action = self.config.config.operation
        spec = BUNNY_OPERATIONS[action]
        values = self.config.config.model_dump(exclude_none=True)

        if action == "list_connection_resources":
            if isinstance(credential, BunnyStreamCredential):
                base = BUNNY_API_BASES["stream"]
                path = f"/library/{credential.library_id}/collections"
                params = {"itemsPerPage": 1}
            else:
                base = BUNNY_API_BASES["core"]
                path = "/pullzone"
                params = {"page": 1, "perPage": 5}
            body = None
        else:
            stream = spec["api"] == "stream"
            if stream != isinstance(credential, BunnyStreamCredential):
                needed = "Stream library" if stream else "account"
                raise ValueError(f"Bunny.net {needed} API key is required for {action}")
            base = BUNNY_API_BASES[spec["api"]]
            path = spec["path"]
            for param in spec["path_fields"]:
                raw, field = param["name"], param["field"]
                value = values.get(field)
                if stream and raw == "libraryId" and value is None:
                    value = credential.library_id
                if value is None or str(value) == "":
                    raise ValueError(f"Bunny.net {raw} is required")
                if action == "shield_get_event_logs_for_shield_zone" and raw == "date":
                    value = _event_log_date(value)
                if ".." in str(value).split("/"):
                    raise ValueError("Bunny.net path traversal is not allowed")
                path = path.replace("{" + raw + "}", quote(str(value), safe=""))
            if re.search(r"\{[^}]+\}", path):
                raise ValueError("Bunny.net path parameter is missing")
            params = (
                _parse_json(values.get("query_json"), "query", object_only=True) or {}
            )
            for param in spec["query_fields"]:
                if param["field"] in values:
                    params[param["name"]] = values[param["field"]]
            body = _parse_json(values.get("body_json"), "body")
            if spec["body_required"] and body is None:
                raise ValueError("Bunny.net request body is required")

        try:
            async with httpx.AsyncClient(timeout=30, follow_redirects=False) as client:
                response = await client.request(
                    spec["method"],
                    base + path,
                    params=params or None,
                    json=body,
                    headers={
                        "AccessKey": credential.access_key,
                        "Accept": "application/json",
                    },
                )
            try:
                payload = response.json() if response.content else {}
            except ValueError:
                payload = {"text": response.text[:65536]}
            failed = response.status_code >= 300
            result: Dict[str, Any] = {
                "status": "error" if failed else "success",
                "action": action,
                "timing_ms": {
                    "api_request": round((time.monotonic() - started) * 1000, 2)
                },
            }
            if failed:
                result.update(
                    status_code=response.status_code,
                    error=(
                        "Bunny.net redirected the request; check the API key and resource access"
                        if response.is_redirect
                        else payload
                    ),
                )
            elif isinstance(payload, list):
                result["data"] = {"items": payload}
            else:
                result["data"] = payload
            if response.headers.get("link"):
                result["pagination_link"] = response.headers["link"]
            return result
        except httpx.HTTPError as exc:
            logger.warning("Bunny.net request failed: %s", type(exc).__name__)
            return {
                "status": "error",
                "action": action,
                "status_code": 502,
                "error": f"Bunny.net request failed ({type(exc).__name__})",
                "timing_ms": {
                    "api_request": round((time.monotonic() - started) * 1000, 2)
                },
            }
