def _operation_model(spec: dict[str, Any]) -> type[BaseModel]:
    fields: dict[str, Any] = {
        "operation": (
            Literal[spec["operation"]],
            Field(
                spec["operation"],
                title=spec["title"],
                json_schema_extra={
                    "const": spec["operation"],
                    "ui:hidden": True,
                    "x-category": spec["category"],
                    "x-display-name": spec["title"],
                    "x-is-trigger": False,
                },
            ),
        )
    }
    for param in spec["path_fields"]:
        name = param["field"]
        optional = spec["api"] == "stream" and param["name"] == "libraryId"
        annotation = int if param["type"] == "integer" else str
        fields[name] = (
            Optional[annotation] if optional else annotation,
            Field(
                None if optional else ...,
                title=param["name"],
                description=(
                    "Defaults to the library ID saved in the Stream credential."
                    if optional
                    else (
                        "Event log date: MM-dd-yyyy, an ISO date, or an ISO timestamp. "
                        "ISO inputs use their calendar date and are sent as MM-dd-yyyy."
                        if spec["operation"] == "shield_get_event_logs_for_shield_zone" and name == "date"
                        else param["description"] or None
                    )
                ),
            ),
        )
    for param in spec["query_fields"]:
        annotation: Any = {
            "boolean": bool,
            "integer": int,
            "number": float,
            "array": list[str],
        }.get(param["type"], str)
        fields[param["field"]] = (
            annotation if param["required"] else Optional[annotation],
            Field(
                ... if param["required"] else None,
                title=param["name"],
                description=param["description"] or None,
            ),
        )
    fields["query_json"] = (
        Optional[str],
        Field(
            None,
            title="Additional query parameters (JSON)",
            description="Optional JSON object for filters not shown above.",
            json_schema_extra={"ui:widget": "textarea"},
        ),
    )
    if spec["has_body"]:
        fields["body_json"] = (
            str if spec["body_required"] else Optional[str],
            Field(
                ... if spec["body_required"] else None,
                title="Request body (JSON)",
                description=f"JSON payload for {spec['method']} {spec['path']}",
                json_schema_extra={"ui:widget": "textarea"},
            ),
        )
    return create_model(
        "Bunny"
        + "".join(part.capitalize() for part in spec["operation"].split("_"))
        + "Config",
        __doc__=spec["title"],
        **fields,
    )


