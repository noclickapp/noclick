def _path_field(variable: str) -> str:
    return "path_" + re.sub(r"[^a-zA-Z0-9]+", "_", variable).lower()


_OPTION_FIELDS = {
    "path_organizationid": ("organizations", None),
    "path_productid": ("products", None),
    "path_configid": ("configs", "path_productid"),
    "path_environmentid": ("environments", "path_productid"),
    "path_settingid": ("settings", "path_configid"),
    "path_segmentid": ("segments", "path_productid"),
}


def _make_config(name: str, operation: dict[str, Any]) -> type[BaseModel]:
    fields: dict[str, tuple[Any, Any]] = {}
    path_variables = re.findall(r"\{([^}]+)\}", operation["path"])
    path_fields = {_path_field(variable) for variable in path_variables}
    for variable in path_variables:
        field_name = _path_field(variable)
        extra: dict[str, Any] = {}
        if field_name in _OPTION_FIELDS:
            resource, dependency = _OPTION_FIELDS[field_name]
            dynamic: dict[str, Any] = {
                "field_name": field_name,
                "placeholder": f"Select {resource[:-1]}...",
                "searchable": True,
                "allow_custom": True,
                "custom_placeholder": f"Or paste {variable}",
            }
            if dependency and dependency in path_fields:
                dynamic["depends_on"] = dependency
            extra["x-dynamic-options"] = dynamic
            extra["x-resource-type"] = f"configcat_{resource[:-1]}"
        fields[field_name] = (
            str,
            Field(
                ...,
                title=variable,
                description=f"ConfigCat {variable} for this operation.",
                json_schema_extra=extra,
            ),
        )
    fields["query_json"] = (
        Optional[str],
        Field(
            None,
            title="Query parameters (JSON)",
            description="Optional JSON object of documented filters, pagination, or other query parameters.",
            json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
        ),
    )
    if operation["body"]:
        fields["body_json"] = (
            str if operation["body_required"] else Optional[str],
            Field(
                ... if operation["body_required"] else None,
                title="Request body (JSON)",
                description="JSON body in the shape shown by ConfigCat's Public Management API reference. JSON Patch operations use an array.",
                json_schema_extra={
                    "ui:widget": "code_editor",
                    "x-code-language": "json",
                },
            ),
        )
    return create_model(
        "ConfigCat" + "".join(part.title() for part in name.split("_")) + "Config",
        __module__=__name__,
        operation=(
            Literal[name],
            Field(
                name,
                title=operation["label"],
                description=operation["description"],
                json_schema_extra={
                    "const": name,
                    "ui:hidden": True,
                    "x-category": operation["category"],
                    "x-display-name": operation["label"],
                    "x-is-trigger": False,
                },
            ),
        ),
        **fields,
    )


CONFIG_MODELS = {name: _make_config(name, op) for name, op in OPERATIONS.items()}
globals().update({model.__name__: model for model in CONFIG_MODELS.values()})
ConfigCatConfig = Annotated[
    Union[tuple(CONFIG_MODELS.values())], Discriminator("operation")
]


