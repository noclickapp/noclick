def _parse_json(raw: str, label: str) -> Any:
    try:
        return json.loads(raw)
    except (TypeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} must be valid JSON") from exc


class ConfigCatNode(WorkflowNode):
    """Manage ConfigCat products, configurations, flags, values, and more."""

    integration_type = "automation-configcat"

    connection_evidence = ConnectionEvidence(
        field="path_productid", noun="products", identity_operation="get_products"
    )
    edit_examples = [
        "List my ConfigCat feature flags",
        "Create a ConfigCat feature flag",
        "Turn on a ConfigCat flag in the test environment",
        "List ConfigCat environments and products",
    ]

    @classmethod
    def get_config_model(cls):
        return ConfigCatNodeConfig

    @classmethod
    async def load_field_options(
        cls,
        field_name: str,
        credential_data: dict[str, Any],
        context: Optional[dict[str, Any]] = None,
        page_token: Optional[str] = None,
        search: Optional[str] = None,
    ) -> dict[str, Any]:
        """Populate product, config, environment, segment, and flag pickers."""
        if field_name not in _OPTION_FIELDS:
            return {"options": []}
        username = credential_data.get("username") if credential_data else None
        password = credential_data.get("password") if credential_data else None
        if not username or not password:
            return {"options": []}
        resource, dependency = _OPTION_FIELDS[field_name]
        ctx = context or {}
        parent = ctx.get(dependency) if dependency else None
        paths = {
            "organizations": "/v1/organizations",
            "products": "/v1/products",
        }
        async with httpx.AsyncClient(timeout=20, follow_redirects=False) as client:

            async def get_rows(path: str) -> list[dict[str, Any]]:
                response = await client.get(
                    API_BASE + path, auth=httpx.BasicAuth(username, password)
                )
                if response.status_code != 200:
                    return []
                data = response.json()
                return (
                    [row for row in data if isinstance(row, dict)]
                    if isinstance(data, list)
                    else []
                )

            if resource in paths:
                rows = await get_rows(paths[resource])
            elif parent:
                prefix = "configs" if resource == "settings" else "products"
                rows = await get_rows(
                    f"/v1/{prefix}/{quote(str(parent), safe='')}/{resource}"
                )
            else:
                # Many routes accept only configId/settingId/environmentId in
                # their path. Search all accessible parents for those pickers.
                products = await get_rows("/v1/products")
                parent_ids = [
                    str(row["productId"]) for row in products if row.get("productId")
                ]
                if resource == "settings":
                    configs = []
                    for product_id in parent_ids:
                        configs.extend(
                            await get_rows(
                                f"/v1/products/{quote(product_id, safe='')}/configs"
                            )
                        )
                    parent_ids = [
                        str(row["configId"]) for row in configs if row.get("configId")
                    ]
                    prefix = "configs"
                else:
                    prefix = "products"
                rows = []
                for parent_id in parent_ids:
                    rows.extend(
                        await get_rows(
                            f"/v1/{prefix}/{quote(parent_id, safe='')}/{resource}"
                        )
                    )
        id_field = {
            "organizations": "organizationId",
            "products": "productId",
            "configs": "configId",
            "environments": "environmentId",
            "settings": "settingId",
            "segments": "segmentId",
        }[resource]
        options = [
            {
                "label": str(row.get("name") or row.get("key") or row[id_field]),
                "value": str(row[id_field]),
            }
            for row in rows
            if isinstance(row, dict) and row.get(id_field)
        ]
        if search:
            options = [o for o in options if search.lower() in o["label"].lower()]
        return {"options": options}

    async def execute(self, inputs: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(self.config, ConfigCatNodeConfig):
            raise ValueError("ConfigCat configuration required")
        credential = self.config.credentials
        if credential is None:
            raise ValueError("Connect ConfigCat Public Management API credentials")
        config = self.config.config
        operation = OPERATIONS[config.operation]
        values = config.model_dump(exclude_none=True, exclude={"operation"})
        path = operation["path"]
        for variable in re.findall(r"\{([^}]+)\}", path):
            value = values.pop(_path_field(variable))
            if not value:
                raise ValueError(f"ConfigCat {variable} is required")
            path = path.replace("{" + variable + "}", quote(str(value), safe=""))
        query_raw = values.pop("query_json", None)
        query = _parse_json(query_raw, "Query parameters") if query_raw else None
        if query is not None and not isinstance(query, dict):
            raise ValueError("Query parameters must be a JSON object")
        body_raw = values.pop("body_json", None)
        if operation["body_required"] and not body_raw:
            raise ValueError("Request body is required")
        request = {"json": _parse_json(body_raw, "Request body")} if body_raw else {}

        started = time.perf_counter()
        async with httpx.AsyncClient(timeout=45, follow_redirects=False) as client:
            response = await client.request(
                operation["method"],
                API_BASE + path,
                auth=httpx.BasicAuth(credential.username, credential.password),
                headers={"Accept": "application/json"},
                params=query,
                **request,
            )
        if response.is_error or response.is_redirect:
            raise ValueError(
                f"ConfigCat API error {response.status_code}: {response.text[:350]}"
            )
        if not response.content:
            data: Any = {"ok": True}
        else:
            try:
                data = response.json()
            except ValueError:
                data = {"text": response.text[:1000]}
        if isinstance(data, list):
            data = {"items": data}
        return {
            "status": "success",
            "operation": config.operation,
            "status_code": response.status_code,
            "data": data,
            "timing_ms": {
                "api_request": round((time.perf_counter() - started) * 1000, 2)
            },
        }
