BASE_URL = "https://api.kvcore.com"
DOCS_URL = "https://documenter.getpostman.com/view/450814/TzsikPdi"


class KvcoreApiToken(BaseModel):
    model_config = ConfigDict(
        title="kvCORE API Token", hide_input_in_errors=True,
        json_schema_extra={
            "x-credential-url": DOCS_URL,
            "x-credential-instructions": "Paste the API token generated by the kvCORE application for your user, without the Bearer prefix. Requests use that user's account permissions. Replace a revoked token here.",
        },
    )
    credential_type: Literal["kvcore_api_token"] = Field(
        "kvcore_api_token", json_schema_extra={"ui:hidden": True})
    api_token: str = Field(
        ..., title="API Token", min_length=1, max_length=8192, repr=False,
        json_schema_extra={"ui:widget": "password"})

    @field_validator("api_token", mode="before")
    @classmethod
    def token(cls, value):
        value = clean_secret(value, field_name="API Token")
        if not value.isascii() or any(ord(c) < 33 or ord(c) == 127 for c in value):
            raise ValueError("Paste the token without a Bearer prefix or whitespace")
        return value


