class KvcoreNode(WorkflowNode):
    integration_type = "automation-kvcore"
    connection_evidence = ConnectionEvidence(
        operation="list_users", noun="users", label_keys=("name", "email", "id"))

    @classmethod
    def get_config_model(cls):
        return KvcoreConfig

    async def execute(self, inputs):
        credential = self.config.credentials
        if credential is None:
            raise ValueError("Connect a kvCORE API token")
        config = self.config.config
        method, template = ROUTES[config.operation]
        values = config.model_dump(exclude_none=True)
        path = template.format(**values)
        path_keys = {part.split("}", 1)[0] for part in template.split("{")[1:]}
        payload = {k: v for k, v in values.items() if k != "operation" and k not in path_keys}
        kwargs = {"json": payload} if method in {"PUT", "POST"} or payload else {}
        try:
            async with guarded_async_client(timeout=30, follow_redirects=False, trust_env=False) as client:
                response = await client.request(method, BASE_URL + path, headers={
                    "Authorization": "Bearer " + credential.api_token,
                    "Content-Type": "application/json", "Accept": "application/json",
                }, **kwargs)
            if response.is_error or response.is_redirect:
                try:
                    body = response.json()
                except ValueError:
                    body = None
                message = (body.get("message") or body.get("error")) if isinstance(body, dict) else None
                return {"status": "error", "http_status": response.status_code,
                        "error": str(message or "kvCORE rejected the request").replace(credential.api_token, "[redacted]")}
            if response.status_code == 204:
                return {"status": "success", "operation": config.operation, "http_status": 204, "data": None}
            if len(response.content) > 10_000_000:
                raise ValueError("kvCORE response exceeds the size limit")
            body = response.json()
            if not isinstance(body, (dict, list)):
                raise ValueError("kvCORE returned an unexpected JSON response")
            if isinstance(body, dict) and (body.get("error") or body.get("success") is False):
                return {"status": "error", "http_status": response.status_code,
                        "error": str(body.get("message") or body.get("error") or "kvCORE rejected the request").replace(credential.api_token, "[redacted]")}
            return {"status": "success", "operation": config.operation,
                    "data": body, "http_status": response.status_code}
        except httpx.HTTPError:
            return {"status": "error", "error": "kvCORE request did not complete; check the account before retrying a write"}
        except ValueError:
            return {"status": "error", "error": "kvCORE returned an invalid response; check the account before retrying a write"}
