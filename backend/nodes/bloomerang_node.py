class ProviderError(ValueError):
    def __init__(self, status=None, message="Bloomerang response could not be verified", rejected=False):
        self.status, self.rejected = status, rejected
        super().__init__(message)


class Session:
    def __init__(self, data):
        self.data = credential(data)
        self.store = self.anchor = None
        self.database = self.user = None
        self.write_attempted = False
        self.acknowledgement = None

    @classmethod
    async def saved(cls, data, *, pool, user_id, credential_id, organization_id=CURRENT_ORGANIZATION, workflow_id=None):
        session = cls(data)
        if pool is None:
            from utils.database_pool import get_native_pool
            pool = get_native_pool()
        session.store = (pool, user_id, credential_id, organization_id, workflow_id)
        session.anchor = await session._saved_state()
        return session

    async def _saved_state(self):
        # Staging owns credential access and workflow fallback. Recheck that
        # policy and the saved grant around every provider request; the node's
        # snapshot additionally detects reconnects and approval revisions.
        pool, user_id, credential_id, organization_id, workflow_id = self.store
        async with pool.acquire() as conn:
            if organization_id is CURRENT_ORGANIZATION:
                from repositories.organization import OrgRepo
                organization_id = await OrgRepo(pool).get_primary_org_id(conn, user_id)
            row = await conn.fetchrow("""
                SELECT c.owner_id, c.credential_type, c.token_version,
                       c.updated_at, c.revoked_at, c.approval_revision
                FROM credentials c WHERE c.id = $1::uuid
            """, credential_id)
        if (row is None or row["credential_type"] != TYPE
                or row["revoked_at"] is not None
                or type(row["token_version"]) is not int or row["token_version"] < 1):
            raise ValueError("Bloomerang credential is unavailable or access denied")
        data = await resolve_credential_with_owner_fallback(
            credential_id, user_id, pool, org_id=organization_id, workflow_id=workflow_id,
        )
        if credential(data) != self.data:
            raise ValueError("Bloomerang credential changed before the request")
        return tuple(row[key] for key in (
            "owner_id", "credential_type", "token_version", "updated_at",
            "revoked_at", "approval_revision",
        )) + (organization_id,)

    async def current(self):
        if self.store is not None and await self._saved_state() != self.anchor:
            raise ValueError("Bloomerang credential authority changed; inspect writes before retrying")

    async def request(self, method, route, *, params=None, body=None, write=False, absent=False):
        try:
            return await asyncio.wait_for(self._request(method, route, params=params, body=body, write=write, absent=absent), timeout=25)
        except TimeoutError:
            raise ProviderError(None, "Bloomerang request deadline exceeded; inspect writes before retrying") from None

    async def _request(self, method, route, *, params=None, body=None, write=False, absent=False):
        if not re.fullmatch(r"/(?:database|user/current|users|groups|constituents|households|interactions|notes|(?:constituent|household|interaction|note)(?:/[1-9][0-9]{0,18})?)", route):
            raise ValueError("Unsupported Bloomerang route")
        if method not in {"GET", "POST", "PUT", "DELETE"} or write != (method != "GET") or (absent and method != "GET"):
            raise ValueError("Unsupported Bloomerang request")
        await self.current()
        if write:
            self.write_attempted = True
        try:
            async with httpx.AsyncClient(verify=True, trust_env=False, follow_redirects=False, timeout=httpx.Timeout(20.0)) as client:
                async with client.stream(method, BASE + route, headers={"X-API-KEY": self.data["api_key"], "Accept": "application/json"}, params=params, json=body) as response:
                    raw = bytearray()
                    async for chunk in response.aiter_bytes():
                        raw.extend(chunk)
                        if len(raw) > 2 * 1024 * 1024:
                            raise ProviderError(response.status_code, "Bloomerang response exceeds the supported size")
                    status = response.status_code
                    if absent and status == 404:
                        await self.current()
                        return None
                    if status != 200:
                        raise ProviderError(status, "Bloomerang request was rejected or did not return a documented completed response")
                    if write:
                        self.acknowledgement = {"http_status": status}
                    try:
                        payload = json.loads(raw, parse_constant=lambda _: (_ for _ in ()).throw(ValueError()))
                    except (ValueError, TypeError, UnicodeError):
                        raise ProviderError(status, "Bloomerang returned an unsupported JSON response") from None
                    if not isinstance(payload, dict):
                        raise ProviderError(status, "Bloomerang returned an unsupported response shape")
                    if payload.get("success") is False or any(payload.get(k) for k in ("error", "errors", "Error", "Errors")):
                        raise ProviderError(status, "Bloomerang returned an error in a successful HTTP response", rejected=True)
                    await self.current()
                    return payload
        except (httpx.HTTPError, OSError):
            raise ProviderError(None, "Bloomerang request outcome is unknown; inspect writes before retrying") from None

    async def bind(self):
        if self.database is None:
            self.database = _database(await self.request("GET", "/database"))
            self.user = _user(await self.request("GET", "/user/current"), active=True)
        return self.database, self.user

    async def verify_binding(self):
        await self.current()
        if _database(await self.request("GET", "/database")) != self.database or _user(await self.request("GET", "/user/current"), active=True) != self.user:
            raise ValueError("Bloomerang database or private-key user changed; inspect writes before retrying")


def _database(row):
    if not isinstance(row, dict):
        raise ValueError("Bloomerang database must be an object")
    out = {"Id": _line(row.get("Id")), "Name": _line(row.get("Name"))}
    for key, allowed in (("Flavor", {"Customer", "Conversions", "Demo"}), ("BaseLicenseProvider", {"Bloomerang", "Firespring", "Benevon"})):
        if row.get(key) is not None:
            if row[key] not in allowed:
                raise ValueError("Bloomerang database metadata is unsupported")
            out[key] = row[key]
    return out


def _user(row, *, active=False):
    if not isinstance(row, dict) or type(row.get("IsActive")) is not bool or (active and row["IsActive"] is not True):
        raise ValueError("Bloomerang private-key user is unavailable")
    out = {"Id": _returned_id(row.get("Id")), "Name": _line(row.get("Name")), "IsActive": row["IsActive"]}
    if row.get("PermissionLevel") is not None:
        if row["PermissionLevel"] not in {"Admin", "Standard", "StandardEditFinancialData"}:
            raise ValueError("Bloomerang user permission metadata is unsupported")
        out["PermissionLevel"] = row["PermissionLevel"]
    return out


def _project(row, kind, *, expected=None, parent=None):
    if kind == "user":
        return _user(row)
    if not isinstance(row, dict):
        raise ValueError("Bloomerang resource must be an object")
    identifier = _returned_id(row.get("Id"))
    if expected is not None and identifier != expected:
        raise ValueError("Bloomerang returned a different resource")
    out = {"Id": identifier}
    if kind in {"interaction", "note"}:
        account = _returned_id(row.get("AccountId"))
        if parent is None or account != parent:
            raise ValueError("Bloomerang resource belongs to a different constituent")
        out["AccountId"], out["Date"] = account, _date(row.get("Date"))
        if kind == "note":
            out["Note"] = _text(row.get("Note"))
        else:
            out["Subject"] = _line(row.get("Subject"))
            if row.get("Channel") not in {"Email", "MassEmail", "Phone", "TextMessage", "Mail", "InPerson", "SocialMedia", "Website", "Twitter", "Other", "EngagementSurveyEmail", "EngagementSurvey"}:
                raise ValueError("Bloomerang interaction channel is unsupported")
            out["Channel"] = row["Channel"]
            out["Purpose"] = _line(row.get("Purpose"))
            if row.get("IsInbound") is not None:
                if type(row["IsInbound"]) is not bool:
                    raise ValueError("Bloomerang interaction inbound flag is invalid")
                out["IsInbound"] = row["IsInbound"]
    elif kind == "group":
        out["Name"] = _line(row.get("Name"))
        if row.get("Description") is not None:
            out["Description"] = _line(row["Description"], 2000) if row["Description"] else ""
    else:
        allowed = {"Household"} if kind == "household" else {"Individual", "Organization"}
        if row.get("Type") not in allowed:
            raise ValueError("Bloomerang resource has an unexpected constituent type")
        out["Type"], out["FullName"] = row["Type"], _line(row.get("FullName"))
        for key in ("SortName", "InformalName", "FormalName", "EnvelopeName", "RecognitionName") if kind == "household" else ("FirstName", "LastName", "MiddleName", "JobTitle", "Employer"):
            if row.get(key) is not None:
                out[key] = _line(row[key]) if row[key] else ""
        if row.get("Status") is not None:
            if row["Status"] not in {"Active", "Inactive", "Deceased"}:
                raise ValueError("Bloomerang constituent status is unsupported")
            out["Status"] = row["Status"]
        if kind == "household":
            out["HeadId"] = _returned_id(row.get("HeadId"))
            members = row.get("MemberIds")
            if not isinstance(members, list) or len(members) > 1000:
                raise ValueError("Bloomerang household members are unsupported")
            out["MemberIds"] = [_returned_id(v) for v in members]
            if len(set(out["MemberIds"])) != len(members) or out["HeadId"] not in out["MemberIds"]:
                raise ValueError("Bloomerang household member IDs are inconsistent")
        elif row.get("HouseholdId") is not None:
            household = _integer(row["HouseholdId"])
            if household:
                out["HouseholdId"] = str(household)
    audit = row.get("AuditTrail")
    if isinstance(audit, dict):
        out["AuditTrail"] = {k: _line(audit[k], 100) for k in ("CreatedDate", "LastModifiedDate") if audit.get(k) is not None}
    return out


def _scope(session, op):
    return {"database": session.database["Id"], "user": session.user["Id"], "config": op.model_dump(exclude={"page_token"})}


def _token(session, scope, offset):
    raw = json.dumps({"scope": scope, "offset": offset}, sort_keys=True, separators=(",", ":")).encode()
    return base64.urlsafe_b64encode(raw + hmac.new(session.data["api_key"].encode(), raw, hashlib.sha256).digest()).decode().rstrip("=")


def _offset(session, scope, token):
    if token is None:
        return 0
    try:
        if not isinstance(token, str) or not 1 <= len(token) <= 4096:
            raise ValueError()
        raw = base64.b64decode(token + "=" * (-len(token) % 4), altchars=b"-_", validate=True)
        data, mac = raw[:-32], raw[-32:]
        if not hmac.compare_digest(mac, hmac.new(session.data["api_key"].encode(), data, hashlib.sha256).digest()):
            raise ValueError()
        parsed = json.loads(data)
        if parsed["scope"] != scope or type(parsed["offset"]) is not int or not 1 <= parsed["offset"] <= MAX_ID:
            raise ValueError()
        return parsed["offset"]
    except Exception:
        raise ValueError("Bloomerang continuation does not match the credential, database, user, operation or filters") from None


def _paging(payload, offset, size):
    if not isinstance(payload, dict) or not isinstance(payload.get("Results"), list):
        raise ValueError("Bloomerang paginated Results are missing")
    total, filtered, start, count = (_integer(payload.get(k)) for k in ("Total", "TotalFiltered", "Start", "ResultCount"))
    rows = payload["Results"]
    if start != offset or count != len(rows) or count > size or not total >= filtered >= start + count:
        raise ValueError("Bloomerang pagination contradicts the requested offset or returned rows")
    more = start + count < filtered
    if more and count == 0:
        raise ValueError("Bloomerang continuation made no progress")
    return rows, {"Total": total, "TotalFiltered": filtered, "Start": start, "ResultCount": count, "has_more": more}


class BloomerangNode(WorkflowNode):
    integration_type = "automation-bloomerang"
    credential_provider_labels = {"bloomerang": "Bloomerang"}
    workflow_credential_refresh = True
    connection_evidence = ConnectionEvidence(noun="users", operation="check_connection", identity_operation="get_current_user", proves="account", label_keys=("Name",))
    edit_examples = ["List individual constituents", "Create a plain constituent note", "Show household counts"]

    @classmethod
    def get_config_model(cls):
        return BloomerangNodeConfig

    @classmethod
    def parse_config(cls, config_data):
        if not isinstance(config_data, dict):
            raise ValueError("Bloomerang configuration is required")
        if config_data.get("credentials") is not None:
            config_data = {**config_data, "credentials": credential(config_data["credentials"])}
        try:
            return TypeAdapter(BloomerangNodeConfig).validate_python(runtime_config_view(config_data, BloomerangNodeConfig))
        except Exception:
            raise ValueError("Bloomerang configuration or credential is invalid") from None

    @classmethod
    async def freshen_credential(cls, credential_data, *, pool=None, user_id=None, credential_id=None):
        data = credential(credential_data)
        if credential_id:
            return {**data, "_bloomerang_session": await Session.saved(data, pool=pool, user_id=user_id, credential_id=credential_id)}
        return data

    @classmethod
    async def validate_credential_access(cls, credential_data, *, validation_context=None):
        data = credential(credential_data)
        try:
            if validation_context is not None:
                result = await validation_context.run_operation("check_connection")
            else:
                # Staging's post-connect hook supplies the credential directly.
                result = await cls._perform(Session(data), CheckConnection())
            valid = True if result.get("identity_verified") is True else None
        except ProviderError as exc:
            valid = False if exc.status in {401, 403} else None
        except ValueError:
            valid = None
        return {"valid": valid, "identity_verified": valid is True,
                "message": "Bloomerang private-key user verified" if valid else "Bloomerang private-key user could not be established"}

    async def execute(self, inputs):
        if self.config is None or self.config.credentials is None:
            raise ValueError("Connect a Bloomerang private CRM API key")
        data = credential(self.config.credentials.model_dump())
        if "credentials" in self.node_data and credential(self.node_data["credentials"]) != data:
            raise ValueError("Bloomerang raw and validated credentials differ")
        session = self.node_data.get("credentials", {}).get("_bloomerang_session")
        if session is not None:
            if not isinstance(session, Session) or session.data != data:
                raise ValueError("Bloomerang current credential context is invalid")
        elif self.node_data.get("credential_id"):
            session = await Session.saved(data, pool=self.node_data.get("_approval_pool"), user_id=self.user_id, credential_id=self.node_data["credential_id"], organization_id=self.organization_id, workflow_id=self.workflow_id)
        else:
            session = Session(data)
        try:
            result = await self._perform(session, self.config.config)
            await session.current()
            output = {"status": "success", "success": True, "action": self.config.config.operation, **result}
        except Exception as exc:
            if session.acknowledgement is not None or (session.write_attempted and (not isinstance(exc, ProviderError) or (not exc.rejected and (exc.status is None or exc.status >= 500 or 200 <= exc.status < 300)))):
                output = {"status": "unknown", "success": False, "action": self.config.config.operation, "acknowledgement": session.acknowledgement, "message": "Bloomerang write outcome could not be verified. Inspect the record before retrying."}
            elif isinstance(exc, ProviderError):
                output = {"status": "error", "success": False, "http_status": exc.status, "message": str(exc)}
            else:
                raise ValueError("Bloomerang response or current credential authority could not be verified") from None
        output = _redact(output, (data["api_key"],))
        await self.emit(output)
        return output

    @classmethod
    async def _get(cls, session, kind, identifier, parent=None):
        return _project(await session.request("GET", f"/{kind}/{identifier}"), kind, expected=identifier, parent=parent)

    @classmethod
    async def _perform(cls, session, op):
        await session.bind()
        name = op.operation
        if name in {"check_connection", "get_current_user", "get_database"}:
            return {"data": [session.user] if name == "check_connection" else session.database if name == "get_database" else session.user, "database_id": session.database["Id"], "identity_verified": True, "proof": "account", "message": "The current private-key user and connected database were read; write permissions are not established"}
        parent = getattr(op, "constituent_id", None)
        if parent is not None:
            await cls._get(session, "constituent", parent)
        if name.startswith("list_"):
            return await cls._list(session, op)
        if name in {"get_constituent_counts", "get_household_counts"}:
            listing = ListConstituents(page_size=1, constituent_type=op.constituent_type) if name == "get_constituent_counts" else ListHouseholds(page_size=1)
            page = await cls._list(session, listing)
            return {"data": {k: page["pagination"][k] for k in ("Total", "TotalFiltered")}, "filters": {"type": getattr(op, "constituent_type", None)}, "count_source": "provider_list_envelope", "database_id": session.database["Id"]}
        verb, kind = name.split("_", 1)
        identifier = getattr(op, kind + "_id", None)
        current = await cls._get(session, kind, identifier, parent=parent) if identifier is not None else None
        if verb == "get":
            return {"data": current, "database_id": session.database["Id"]}
        if verb in {"update", "delete"}:
            expected_key = "Note" if kind == "note" else "Subject" if kind == "interaction" else "FullName"
            expected_value = getattr(op, "expected_note" if kind == "note" else "expected_subject" if kind == "interaction" else "expected_full_name")
            if current.get(expected_key) != expected_value:
                raise ValueError("The current record differs from the configured confirmation")
        await session.verify_binding()
        if verb == "delete":
            ack = await session.request("DELETE", f"/{kind}/{identifier}", write=True)
            if _returned_id(ack.get("Id")) != identifier or ack.get("Deleted") is not True:
                raise ValueError("Bloomerang deletion acknowledgement could not be verified")
            type_label = _line(ack.get("Type"))  # Public spec does not enumerate Type.
            if await session.request("GET", f"/{kind}/{identifier}", absent=True) is not None:
                raise ValueError("Deleted record is still present")
            await session.verify_binding()
            return {"data": {"Id": identifier, "Type": type_label, "Deleted": True}, "http_status": 200, "readback_verified": True, "absence_http_status": 404, "members_preserved": kind == "household", "database_id": session.database["Id"]}
        body = {}
        if kind == "constituent":
            constituent_type = op.constituent_type if verb == "create" else current["Type"]
            body["Type"] = constituent_type
            if constituent_type == "Individual":
                if op.full_name is not None:
                    raise ValueError("An individual name uses FirstName and LastName")
                body.update({"FirstName": op.first_name if op.first_name is not None else current.get("FirstName"), "LastName": op.last_name if op.last_name is not None else current.get("LastName")})
                for value in (body["FirstName"], body["LastName"]):
                    _line(value)
            else:
                if op.first_name is not None or op.last_name is not None:
                    raise ValueError("An organization name uses FullName")
                body["FullName"] = _line(op.full_name if op.full_name is not None else current["FullName"])
        elif kind == "household":
            names = ("FullName", "SortName", "InformalName", "FormalName", "EnvelopeName", "RecognitionName")
            body = {key: op.full_name if verb == "create" or key == "FullName" else _line(current.get(key)) for key in names}
            if verb == "create":
                body["Head"] = {"Type": "Individual", "FirstName": op.head_first_name, "LastName": op.head_last_name}
        elif kind == "interaction":
            body = {"AccountId": int(parent), "Date": op.interaction_date, "Channel": op.channel, "Purpose": op.purpose, "Subject": op.subject} if verb == "create" else {"Subject": op.subject}
        elif kind == "note":
            body = {"AccountId": int(parent), "Date": op.note_date, "Note": op.note} if verb == "create" else {"Note": op.note}
        else:
            raise ValueError("Unsupported Bloomerang operation")
        row = await session.request("POST" if verb == "create" else "PUT", f"/{kind}" if verb == "create" else f"/{kind}/{identifier}", body=body, write=True)
        written = _project(row, kind, expected=identifier, parent=parent)
        identifier = written["Id"]
        readback = await cls._get(session, kind, identifier, parent=parent)
        checked = {k: v for k, v in body.items() if k != "Head"}
        if kind == "note" or kind == "interaction":
            checked.pop("AccountId", None)
        if any(written.get(k) != v or readback.get(k) != v for k, v in checked.items()):
            raise ValueError("Bloomerang written metadata could not be read back")
        if kind == "household" and verb == "create":
            if readback["MemberIds"] != [readback["HeadId"]] or written["HeadId"] != readback["HeadId"]:
                raise ValueError("New household head/member IDs could not be verified")
            head = await cls._get(session, "constituent", readback["HeadId"])
            if head.get("HouseholdId") != identifier or head.get("FirstName") != op.head_first_name or head.get("LastName") != op.head_last_name:
                raise ValueError("New household head could not be verified")
        await session.verify_binding()
        return {"data": readback, "http_status": 200, "readback_verified": True, "database_id": session.database["Id"], "created_head_id": readback.get("HeadId") if kind == "household" and verb == "create" else None}

    @classmethod
    async def _list(cls, session, op):
        kind = {"list_constituents": "constituent", "list_households": "household", "list_interactions": "interaction", "list_notes": "note", "list_users": "user", "list_groups": "group"}[op.operation]
        scope = _scope(session, op)
        offset = _offset(session, scope, op.page_token)
        params = {"skip": offset, "take": op.page_size}
        if kind == "constituent":
            params.update({"orderBy": "Id", "orderDirection": "Asc"})
            if op.constituent_type is not None:
                params["type"] = op.constituent_type
        if kind in {"interaction", "note"}:
            params.update({"constituent": op.constituent_id, "orderBy": "CreatedDate", "orderDirection": "Asc"})
        if kind == "user":
            params["isActive"] = str(op.active_only).lower()
        payload = await session.request("GET", "/" + {"constituent": "constituents", "household": "households", "interaction": "interactions", "note": "notes", "user": "users", "group": "groups"}[kind], params=params)
        rows, pagination = _paging(payload, offset, op.page_size)
        out, identifiers = [], set()
        for row in rows:
            projected = _project(row, kind, parent=getattr(op, "constituent_id", None))
            if projected["Id"] in identifiers:
                raise ValueError("Bloomerang page contains duplicate API IDs")
            if kind == "constituent" and op.constituent_type is not None and projected["Type"] != op.constituent_type:
                raise ValueError("Bloomerang returned a constituent outside the type filter")
            if kind == "user" and projected["IsActive"] != op.active_only:
                raise ValueError("Bloomerang returned a user outside the active filter")
            identifiers.add(projected["Id"])
            out.append(projected)
        return {"data": out, "pagination": pagination, "next_page_token": _token(session, scope, offset + len(rows)) if pagination["has_more"] else None, "database_id": session.database["Id"]}

    @classmethod
    async def load_field_options(cls, field_name, credential_data, context=None, *, page_token=None, search=None):
        if field_name not in {"constituent_id", "household_id", "interaction_id", "note_id"}:
            return []
        data = credential(credential_data)
        session = credential_data.get("_bloomerang_session")
        if session is not None and (not isinstance(session, Session) or session.data != data):
            raise ValueError("Bloomerang current credential context is invalid")
        session = session or Session(data)
        context = context or {}
        parent = context.get("constituent_id")
        if field_name in {"interaction_id", "note_id"}:
            parent = _id(parent)
        await session.bind()
        if field_name in {"interaction_id", "note_id"}:
            await cls._get(session, "constituent", parent)
        query = search if search is not None else context.get("search")
        search = _line(query).casefold() if query else None
        listing = ListConstituents() if field_name == "constituent_id" else ListHouseholds() if field_name == "household_id" else ListInteractions(constituent_id=parent) if field_name == "interaction_id" else ListNotes(constituent_id=parent)
        listing_scope = _scope(session, listing)
        lookup_scope = {**listing_scope, "purpose": field_name + "_options", "search": search}
        offset = _offset(session, lookup_scope, page_token)
        out, identifiers, next_token = [], set(), None
        for _ in range(20):
            native = _token(session, listing_scope, offset) if offset else None
            page = await cls._list(session, listing.model_copy(update={"page_token": native}))
            for row in page["data"]:
                if row["Id"] in identifiers:
                    raise ValueError("Bloomerang lookup repeats a resource ID across pages")
                identifiers.add(row["Id"])
                label = row.get("FullName") or row.get("Subject") or row.get("Date") or row["Id"]
                if search is None or search in label.casefold():
                    out.append({"value": row["Id"], "label": label, "metadata": {"database_id": session.database["Id"], "constituent_id": row.get("AccountId")}})
            offset += page["pagination"]["ResultCount"]
            next_token = _token(session, lookup_scope, offset) if page["pagination"]["has_more"] else None
            if len(out) >= 1000 or next_token is None:
                break
        await session.current()
        return {"options": _redact(out, (data["api_key"],)), "next_page_token": next_token}
