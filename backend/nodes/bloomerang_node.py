MAX_ID = 2**63 - 1


def _id(value):
    if not isinstance(value, str) or not re.fullmatch(r"[1-9][0-9]{0,18}", value) or int(value) > MAX_ID:
        raise ValueError("A positive decimal Bloomerang API ID is required, not an account number")
    return value


def _integer(value, minimum=0, maximum=MAX_ID):
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError("Bloomerang returned an invalid integer")
    return value


def _returned_id(value):
    return str(_integer(value, 1))


def _line(value, maximum=200):
    if not isinstance(value, str) or not value.strip() or len(value) > maximum or any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError("A nonempty single-line value is required")
    return value


def _text(value):
    if not isinstance(value, str) or not value.strip() or len(value) > 10000 or any((ord(c) < 32 and c not in "\r\n\t") or ord(c) == 127 for c in value):
        raise ValueError("A nonempty plain note of at most 10000 characters is required")
    return value


def _optional_line(value):
    return _line(value) if value is not None else None


def _name_value(value):
    # A one-argument validator; _line's optional limit is not ValidationInfo.
    return _line(value)


def _date(value):
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
        raise ValueError("A YYYY-MM-DD calendar date is required")
    date.fromisoformat(value)
    return value


def _redact(value, secrets):
    if isinstance(value, str):
        for secret in secrets:
            value = value.replace(secret, "[redacted]")
        return value
    if isinstance(value, list):
        return [_redact(v, secrets) for v in value]
    if isinstance(value, dict):
        return {_redact(k, secrets): _redact(v, secrets) for k, v in value.items()}
    return value


