    if not isinstance(data, dict) or data.get("credential_type") != TYPE:
        raise ValueError("An explicit Bloomerang private CRM API-key credential is required")
    try:
        return BloomerangPrivateApiKeyCredential.model_validate({k: data[k] for k in FIELDS if k in data}).model_dump()
    except Exception:
        raise ValueError("Bloomerang credential is invalid") from None


