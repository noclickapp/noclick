class DeelAPITokenCredential(BaseModel):
    """A token generated by an organization or IT developer administrator."""

    credential_type: Literal["deel_api_token"] = Field(
        "deel_api_token", json_schema_extra={"ui:hidden": True}
    )
    api_token: str = Field(
        ..., title="API Token",
        description="Your Deel organization or personal API token.",
        json_schema_extra={"ui:widget": "password"},
    )
    model_config = ConfigDict(
        title="Deel API Token",
        json_schema_extra={
            "x-credential-url": "https://developer.deel.com/api/authentication",
            "x-credential-instructions": "In Deel, open More → Developer → Access Tokens, generate an organization or personal token, and paste it here. Select people:read for connection verification, plus the scopes listed in Deel's API reference for the actions you use.",
        },
    )


def _operation(name: str, label: str, category: str):
    return Field(name, title=label, json_schema_extra={
        "const": name, "ui:hidden": True, "x-display-name": label,
        "x-category": category, "x-is-trigger": False,
    })


def _json_field(title: str, description: str, default=...):
    return Field(default, title=title, description=description,
                 json_schema_extra={"ui:widget": "textarea"})


