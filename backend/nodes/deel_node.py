def _parse_json(value, expected, title):
    try:
        parsed = json.loads(value) if isinstance(value, str) else value
    except (ValueError, TypeError) as exc:
        raise ValueError(f"{title} must contain valid JSON") from exc
    if not isinstance(parsed, expected):
        raise ValueError(f"{title} must be a JSON {expected.__name__}")
    if expected is list:
        item_type = str if title == "child_hris_profile_ids_json" else dict
        if any(not isinstance(item, item_type) for item in parsed):
            raise ValueError(f"{title} contains an invalid item")
    return parsed


class DeelNode(WorkflowNode):
    """Sync people and maintain organization and reporting structures in Deel."""
    integration_type = "automation-deel"
    credential_provider_labels = {"deel": "Deel Account"}
    auto_select_credential = False

    connection_evidence = ConnectionEvidence(
        operation="list_people", noun="people",
        label_keys=("full_name", "preferred_first_name", "first_name", "id"),
    )
    edit_examples = [
        "Sync employee and contractor records from Deel",
        "Move a person to a different department",
        "Update departments and teams in my organization structure",
        "Create a person in Deel without sending an invitation",
        "Update a person's reporting relationships",
    ]

    @classmethod
    def get_config_model(cls):
        return DeelNodeConfig

    async def execute(self, inputs: Dict[str, Any]) -> Dict[str, Any]:
        if not isinstance(self.config, DeelNodeConfig):
            raise ValueError("Valid Deel configuration is required")
        if not self.config.credentials:
            raise ValueError("Credentials are required. Add your Deel API token.")
        config = self.config.config
        operation = config.operation
        method, template, path_fields, query_fields = ROUTES[operation]
        values = config.model_dump(mode="json", exclude_none=True)
        values.pop("operation")
        path = template
        for field in path_fields:
            path = path.replace("{" + field + "}", quote(str(values.pop(field)), safe=""))
        params = {field: values.pop(field) for field in query_fields if field in values}
        for key in list(values):
            if key.endswith("_json"):
                expected = list if key in ("teams_json", "phone_numbers_json", "child_hris_profile_ids_json") else dict
                values[key[:-5]] = _parse_json(values.pop(key), expected, key)
        if operation == "create_person":
            values = {
                "client": {"team": {"id": values.pop("team_id")},
                           "legal_entity": {"id": values.pop("legal_entity_id")}},
                "person": {key: values[key] for key in ("first_name", "last_name", "email", "start_date")},
                **({"invitation": values["invitation"]} if "invitation" in values else {}),
            }
        elif operation == "update_personal_information" and not values:
            raise ValueError("Provide at least one personal information field to update")
        body = {"data": values} if method in ("POST", "PUT", "PATCH") else None
        start = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.request(
                    method, DEEL_API_BASE + path,
                    headers={"Authorization": f"Bearer {self.config.credentials.api_token}",
                             "Accept": "application/json"},
                    params=params, json=body,
                )
            timing = {"api_request": round((time.perf_counter() - start) * 1000, 2)}
            if response.status_code >= 400:
                return {"status": "error", "action": operation,
                        "status_code": response.status_code, "error": response.text,
                        "timing_ms": timing}
            # Personal information updates return 204 with no response body.
            payload = {} if response.status_code == 204 else response.json()
            if not isinstance(payload, dict):
                raise ValueError("Deel returned an invalid response object")
            # Preserve Deel's complete envelope, including page and nested employment data.
            return {"status": "success", "action": operation, "data": payload,
                    "status_code": response.status_code, "timing_ms": timing}
        except httpx.RequestError as exc:
            # Never include the credential-bearing request or headers in errors.
            return {"status": "error", "action": operation,
                    "error": f"Deel request failed ({type(exc).__name__})",
                    "timing_ms": {"api_request": round((time.perf_counter() - start) * 1000, 2)}}
