"""Deel HRIS automation with a pasted organization or personal API token.

Each operation maps to one documented Deel REST endpoint (stable 2026-01-01).
Lists expose one page and preserve pagination for incremental workforce syncs.
Docs: https://developer.deel.com/api/stable/llms.txt
Deel also offers webhooks; this node provides request/response actions only.
"""

