class AlgoliaNode(WorkflowNode):
    integration_type = "automation-algolia"
    connection_evidence = ConnectionEvidence(operation="search_list_indices", noun="application")
    edit_examples = [
        "Search an Algolia index", "Add a record to Algolia", "List Algolia indices",
        "Get search analytics", "Create a query suggestion configuration",
    ]

    @classmethod
    def get_config_model(cls):
        return AlgoliaNodeConfig

    @staticmethod
    def _json(raw: str, label: str) -> Any:
        try:
            return json.loads(raw)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{label} must be valid JSON") from exc

    @staticmethod
    def _base_url(family: str, credential: AlgoliaApiKeyCredential) -> str:
        if family in APP_HOST_FAMILIES:
            url = f"https://{credential.application_id}.algolia.net"
            return url + ("/agent-studio" if family == "agent-studio" else "")
        host = REGIONAL_HOSTS[family]
        region = "de" if credential.region == "eu" and family in EU_DE_FAMILIES else credential.region
        return "https://" + host.format(region=region)

    @staticmethod
    async def _request(op: dict[str, Any], credential: AlgoliaApiKeyCredential,
                       path: str, params: dict[str, Any], headers: dict[str, str],
                       body: Any) -> Any:
        url = AlgoliaNode._base_url(op["family"], credential) + path
        request_headers = {
            "X-Algolia-Application-Id": credential.application_id,
            "X-Algolia-API-Key": credential.api_key,
            "Accept": "application/json",
            **headers,
        }
        kwargs: dict[str, Any] = {"params": params or None, "headers": request_headers}
        if body is not None:
            kwargs["json"] = body
        async with httpx.AsyncClient(timeout=60, follow_redirects=False) as client:
            response = await client.request(op["method"], url, **kwargs)
        if response.is_error or response.is_redirect:
            try:
                detail = response.json()
                message = (detail.get("message") or detail.get("error")) if isinstance(detail, dict) else None
            except ValueError:
                message = None
            raise ValueError(f"Algolia API error {response.status_code}: {message or 'request failed'}")
        if not response.content:
            return {"ok": True}
        if "json" in response.headers.get("content-type", "") or response.content[:1] in (b"{", b"["):
            return response.json()
        return BinaryOutput(
            data=response.content,
            content_type=response.headers.get("content-type", "application/octet-stream"),
            filename="algolia-response",
        )

    async def execute(self, inputs: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(self.config, AlgoliaNodeConfig):
            raise ValueError("Algolia configuration required")
        credential = self.config.credentials
        if credential is None:
            raise ValueError("Connect an Algolia API key")
        config = self.config.config
        op = OPERATIONS[config.operation]
        values = config.model_dump(exclude_none=True, exclude={"operation"})
        path = op["path"]
        for variable in re.findall(r"\{([^}]+)\}", path):
            path = path.replace("{" + variable + "}", quote(str(values.pop(variable)), safe=""))
        raw_query = values.pop("query_json", None)
        params = self._json(raw_query, "Other Query Parameters JSON") if raw_query else {}
        if not isinstance(params, dict):
            raise ValueError("Other Query Parameters JSON must be an object")
        headers: dict[str, str] = {}
        for parameter in op["required_params"]:
            value = values.pop(_parameter_field(parameter["name"], parameter["in"]))
            if parameter["in"] == "query":
                params[parameter["name"]] = value
            else:
                headers[parameter["name"]] = value
        raw_body = values.pop("body_json", None)
        body = self._json(raw_body, "Request Body JSON") if raw_body is not None else None
        data = await self._request(op, credential, path, params, headers, body)
        return {"status": "success", "operation": config.operation, "data": data}
