class AlgoliaApiKeyCredential(BaseModel):
    credential_type: Literal["algolia_api_key"] = Field(
        "algolia_api_key", json_schema_extra={"ui:hidden": True}
    )
    application_id: str = Field(..., title="Application ID")
    api_key: str = Field(..., title="API Key", json_schema_extra={"ui:widget": "password"})
    region: Literal["us", "eu"] = Field(
        "us", title="Region", description="Select the Algolia analytics and ingestion region."
    )
    model_config = ConfigDict(title="Algolia API Key", json_schema_extra={
        "x-credential-url": "https://dashboard.algolia.com/account/api-keys",
        "x-credential-instructions": (
            "Copy your application ID and an API key with the permissions needed for your actions "
            "from the Algolia dashboard. Use an admin key only when required."
        ),
    })

    @field_validator("application_id")
    @classmethod
    def validate_application_id(cls, value: str) -> str:
        if not re.fullmatch(r"[A-Za-z0-9_-]{2,64}", value):
            raise ValueError("Invalid Algolia application ID")
        return value


def _parameter_field(name: str, location: str) -> str:
    return location + "_" + re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_").lower()


def _make_config(name: str, op: dict[str, Any]) -> type[BaseModel]:
    fields: dict[str, tuple[Any, Any]] = {}
    for variable in re.findall(r"\{([^}]+)\}", op["path"]):
        fields[variable] = (str, Field(..., title=variable))
    for parameter in op["required_params"]:
        fields[_parameter_field(parameter["name"], parameter["in"])] = (
            str, Field(..., title=parameter["name"])
        )
    fields["query_json"] = (Optional[str], Field(
        None, title="Other Query Parameters JSON",
        description="Optional Algolia query parameters as a JSON object.",
        json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
    ))
    if op["has_body"]:
        fields["body_json"] = (str if op["body_required"] else Optional[str], Field(
            ... if op["body_required"] else None,
            title="Request Body JSON",
            description="JSON body defined by the Algolia REST API for this action.",
            json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
        ))
    return create_model(
        "Algolia" + "".join(part.title() for part in name.split("_")) + "Config",
        __module__=__name__,
        operation=(Literal[name], Field(
            name, title=op["label"], description=op["description"],
            json_schema_extra={"const": name, "ui:hidden": True,
                               "x-category": op["family"].replace("-", " ").title(),
                               "x-is-trigger": False, "x-display-name": op["label"]},
        )),
        **fields,
    )


CONFIG_MODELS = {name: _make_config(name, op) for name, op in OPERATIONS.items()}
globals().update({model.__name__: model for model in CONFIG_MODELS.values()})
AlgoliaConfig = Annotated[Union[tuple(CONFIG_MODELS.values())], Discriminator("operation")]


