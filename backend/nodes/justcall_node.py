class JustCallAPIKeyCredential(BaseModel):
    model_config = ConfigDict(
        title="JustCall API Key",
        hide_input_in_errors=True,
        json_schema_extra={
            "x-credential-url": "https://developer.justcall.io/reference/authentication",
            "x-credential-instructions": "In JustCall, open your profile → APIs and Webhooks and copy your existing API key and secret. Paste each separately below. API access requires a JustCall Team plan or above. NoClick checks the account by reading its users.",
        },
    )
    credential_type: Literal["justcall_api_key"] = Field(
        "justcall_api_key", json_schema_extra={"ui:hidden": True}
    )
    api_key: str = Field(
        ...,
        title="API key",
        min_length=1,
        max_length=4096,
        json_schema_extra={"ui:widget": "password"},
    )
    api_secret: str = Field(
        ...,
        title="API secret",
        min_length=1,
        max_length=4096,
        json_schema_extra={"ui:widget": "password"},
    )

    @field_validator("api_key", "api_secret", mode="before")
    @classmethod
    def secret(cls, value, info):
        value = clean_secret(value, field_name=info.field_name)
        if not value.isascii() or any(c.isspace() for c in value) or ":" in value:
            raise ValueError(
                "Paste the key or secret separately, without a header or colon"
            )
        return value


