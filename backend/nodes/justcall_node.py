def _redact(value, credential):
    if isinstance(value, str):
        for secret in sorted(
            (credential.api_key, credential.api_secret), key=len, reverse=True
        ):
            value = value.replace(secret, "[redacted]")
        return value
    if isinstance(value, dict):
        return {key: _redact(item, credential) for key, item in value.items()}
    if isinstance(value, list):
        return [_redact(item, credential) for item in value]
    return value


class JustCallNode(WorkflowNode):
    integration_type = "automation-justcall"
    connection_evidence = ConnectionEvidence(
        noun="JustCall users",
        operation="list_users",
        label_keys=("name", "email", "id"),
    )

    @classmethod
    def get_config_model(cls):
        return JustCallFullConfig

    async def execute(self, context):
        if not self.config.credentials:
            raise ValueError("Connect a JustCall API key and secret")
        credential = self.config.credentials
        config = self.config.config
        method, path, query_fields, body_fields = ROUTES[config.operation]
        values = config.model_dump(exclude_none=True, exclude={"operation"})
        if "{id}" in path:
            path = path.replace("{id}", str(values["id"]))
        params = {key: values[key] for key in query_fields if key in values}
        body = {key: values[key] for key in body_fields if key in values}
        headers = {
            "Authorization": credential.api_key + ":" + credential.api_secret,
            "Accept": "application/json",
        }
        try:
            async with guarded_async_client(
                timeout=30, follow_redirects=False, trust_env=False
            ) as client:
                response = await client.request(
                    method,
                    "https://api.justcall.io" + path,
                    headers=headers,
                    params=params,
                    **({"json": body} if body_fields else {}),
                )
        except (httpx.HTTPError, SSRFError):
            return {
                "status": "error",
                "error": "JustCall request could not be completed; check the provider before retrying a write",
            }
        if not 200 <= response.status_code < 300:
            try:
                error = response.json()
                error = (
                    error.get("message") or error.get("error") or response.reason_phrase
                    if isinstance(error, dict)
                    else response.reason_phrase
                )
            except ValueError:
                error = response.reason_phrase
            return {
                "status": "error",
                "status_code": response.status_code,
                "error": _redact(str(error)[:2000], credential),
            }
        if len(response.content) > 10_000_000:
            raise ValueError("JustCall response exceeds the JSON size limit")
        try:
            data = response.json()
        except ValueError:
            raise ValueError("JustCall returned an invalid JSON response") from None
        if not isinstance(data, (dict, list)):
            raise ValueError("JustCall returned an unexpected JSON response")
        if isinstance(data, dict) and (
            data.get("success") is False
            or data.get("status") in ("error", "failed")
            or data.get("error")
        ):
            return {
                "status": "error",
                "status_code": response.status_code,
                "error": _redact(
                    str(
                        data.get("message")
                        or data.get("error")
                        or "JustCall rejected the request"
                    ),
                    credential,
                ),
            }
        return {"status": "success", "data": _redact(data, credential)}
