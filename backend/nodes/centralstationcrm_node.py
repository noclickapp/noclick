def _title(value: str) -> str:
    return value.replace("_", " ").replace("[", " ").replace("]", "").title()


def _make_config(key: str, operation: dict[str, Any]) -> type[BaseModel]:
    metadata = {
        "const": key,
        "ui:hidden": True,
        "x-display-name": operation["label"],
        "x-category": operation["category"],
        "x-is-trigger": False,
    }
    if operation["method"] == "POST" and operation["label"].lower().startswith("create"):
        metadata["x-creates-resource"] = True
        metadata["x-resource-type"] = "centralstationcrm_" + key
    fields: dict[str, tuple[Any, Any]] = {
        "operation": (Literal[key], Field(key, title=operation["label"], json_schema_extra=metadata)),
    }
    for name in re.findall(r"\{([^}]+)\}", operation["path"]):
        fields[name] = (str, Field(..., title=_title(name), min_length=1))
    for name in operation["required_query_params"]:
        fields["query_" + re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")] = (
            str, Field(..., title=_title(name), min_length=1)
        )
    if "page" in operation["query_params"]:
        fields["page"] = (Optional[int], Field(None, title="Page", ge=1))
    if "perpage" in operation["query_params"]:
        fields["perpage"] = (Optional[int], Field(None, title="Page Size", ge=1, le=250))
    optional_query = set(operation["query_params"]) - set(operation["required_query_params"]) - {"page", "perpage"}
    if optional_query:
        fields["query_json"] = (
            Optional[str], Field(
                None, title="Other Query Parameters JSON",
                description="Optional API query keys: " + ", ".join(sorted(optional_query)),
                json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
            ),
        )
    if operation["has_body"]:
        hint = "Top-level keys: " + ", ".join(operation["body_keys"]) if operation["body_keys"] else "Use the request schema in the API reference."
        fields["payload_json"] = (
            str, Field(
                ..., title="Request JSON", description=hint,
                json_schema_extra={"ui:widget": "code_editor", "x-code-language": "json"},
            ),
        )
    return create_model(
        "CentralStationCRM" + "".join(part.title() for part in key.split("_")) + "Config",
        __module__=__name__, **fields,
    )


