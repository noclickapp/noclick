def _json_object(value: str, label: str) -> dict[str, Any]:
    try:
        parsed = json.loads(value)
    except (TypeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} must be valid JSON") from exc
    if not isinstance(parsed, dict):
        raise ValueError(f"{label} must be a JSON object")
    return parsed


class CentralStationCRMNode(WorkflowNode):
    integration_type = "automation-centralstationcrm"
    connection_evidence = ConnectionEvidence(operation="check_connection", noun="account")
    edit_examples = [
        "List CentralStationCRM contacts and companies",
        "Create a contact and add a task",
        "Search opportunities and update a deal",
        "Get recent activities and project details",
    ]

    @classmethod
    def get_config_model(cls):
        return CentralStationCRMNodeConfig

    @staticmethod
    async def _request(
        credential: CentralStationCRMApiKeyCredential, method: str, path: str,
        *, params: dict[str, Any] | None = None, body: dict[str, Any] | None = None,
    ) -> Any:
        async with httpx.AsyncClient(timeout=45.0) as client:
            response = await client.request(
                method, BASE_URL + path,
                params=params, json=body,
                headers={"X-apikey": credential.api_key, "Accept": "application/json"},
            )
        if response.content:
            try:
                data: Any = response.json()
            except ValueError:
                data = {"text": response.text}
        else:
            data = {"ok": True}
        if response.is_error:
            detail = data.get("error") or data.get("message") if isinstance(data, dict) else None
            if not isinstance(detail, str):
                detail = "request failed"
            detail = detail.replace(credential.api_key, "[redacted]")
            raise ValueError(f"CentralStationCRM API error {response.status_code}: {detail}")
        return data

    async def execute(self, inputs: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(self.config, CentralStationCRMNodeConfig):
            raise ValueError("CentralStationCRM configuration required")
        credential = self.config.credentials
        if credential is None:
            raise ValueError("Connect a CentralStationCRM API key")
        config = self.config.config
        operation = OPERATIONS[config.operation]
        values = config.model_dump(exclude_none=True, exclude={"operation"})
        path = operation["path"]
        for name in re.findall(r"\{([^}]+)\}", path):
            path = path.replace("{" + name + "}", quote(str(values.pop(name)), safe=""))
        params = _json_object(values.pop("query_json"), "Query Parameters JSON") if "query_json" in values else {}
        for name in operation["required_query_params"]:
            key = "query_" + re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
            params[name] = values.pop(key)
        for name in ("page", "perpage"):
            if name in values:
                params[name] = values.pop(name)
        body = _json_object(values.pop("payload_json"), "Request JSON") if "payload_json" in values else None
        data = await self._request(credential, operation["method"], path, params=params or None, body=body)
        return {"status": "success", "operation": config.operation, "data": data}
