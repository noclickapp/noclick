"""
Pipedrive CRM automation node.

Full-coverage workflow integration with the Pipedrive REST API (v1 + v2). Every
currently-offered documented endpoint (~294 operations across 22 resources) is
exposed via a declarative registry (``OP_SPECS`` below) that programmatically
generates one Pydantic config model per operation and drives a single generic,
version-aware dispatcher. Resources covered: Deals (+ fields, products, followers,
discounts, installments, participants, flow), Persons & Organizations (+ fields,
followers, relationships, sub-collections), Leads (+ labels, sources), Activities
(+ types, fields), Notes (+ comments), Pipelines, Stages, Products (+ fields,
variations, followers), Goals, Users, Roles / Permission Sets / Legacy Teams,
Files, Mail, Filters, Search, Webhooks, Projects & Tasks, Call Logs, Channels,
and more. Plus per-event webhook Triggers — one operation per object/action
("On Deal Created", "On Person Updated", …, 10 objects × create/change/delete +
an "On Any Pipedrive Event" wildcard) so each is a distinct, self-describing
trigger node.

Excluded by design: the removed Subscriptions API (recurring/installment — now
404, superseded by Deals installments) and binary file-upload endpoints (need
multipart, which the JSON request path does not carry).

Authentication: OAuth 2.0 (Authorization: Bearer, recommended) or API token
(x-api-token header + company domain). OAuth credentials carry an ``api_domain``
(the company-specific base URL); API-token credentials carry a ``company_domain``.
API Base URL: https://{company_domain}.pipedrive.com/api/v2 (core) and /api/v1.
Documentation: https://developers.pipedrive.com/docs/api/v1
"""

