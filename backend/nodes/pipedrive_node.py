    """json_schema_extra for a generated field: the dynamic-options dropdown flag
    and the date-picker widget where applicable. Placeholders ride on each field's
    ``description`` (rendered as the input placeholder) — no renderer change."""
    extra: Dict[str, Any] = dict(_dyn_extra(name) or {})
