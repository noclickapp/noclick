def _base_url(company_domain: str, version: str) -> str:
    """Build the Pipedrive base URL for a given API version (v1 or v2).

    Accepts either a bare subdomain ('acme'), a full host ('acme.pipedrive.com'),
    or a full origin ('https://acme.pipedrive.com' — the OAuth api_domain).
    """
    domain = normalize_provider_subdomain(
        company_domain, "pipedrive.com", field_name="Pipedrive company domain"
    )
    return f"https://{domain}.pipedrive.com/api/{version}"


def _coerce_value(value: Any, ftype: str) -> Any:
    """Coerce a string form value into the JSON type the API expects.

    Object/array fields accept JSON text; integer/number/boolean are parsed.
    Bad input raises (no silent fallback) so the user sees a real error.
    """
    if isinstance(value, str):
        v = value.strip()
        if v == "":
            return None
    else:
        v = value
    if ftype == "integer":
        return int(v)
    if ftype == "number":
        return float(v)
    if ftype == "boolean":
        return str(v).strip().lower() in ("true", "1", "yes")
    if ftype in ("object", "array"):
        return _json.loads(v) if isinstance(v, str) else v
    return v


async def _pipedrive_request(
    company_domain: str,
    api_token: str,
    method: str,
    endpoint: str,
    version: str = "v2",
    params: Optional[Dict[str, Any]] = None,
    json_body: Optional[Dict[str, Any]] = None,
    action_name: str = "request",
    auth_bearer: bool = False,
) -> Dict[str, Any]:
    """Make an authenticated Pipedrive request and return a structured result.

    API-token credentials authenticate via the ``x-api-token`` header; OAuth
    credentials authenticate via ``Authorization: Bearer`` (auth_bearer=True).
    """
    url = f"{_base_url(company_domain, version)}{endpoint}"
    headers = {
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    if auth_bearer:
        headers["Authorization"] = f"Bearer {api_token}"
    else:
        headers["x-api-token"] = api_token
    if isinstance(json_body, dict):
        json_body = {k: v for k, v in json_body.items() if v is not None}
    if params:
        params = {k: v for k, v in params.items() if v not in (None, "")}

    start = time.time()
    async with httpx.AsyncClient(timeout=30.0) as client:
        try:
            response = await client.request(
                method=method, url=url, headers=headers, params=params, json=json_body
            )
            api_ms = round((time.time() - start) * 1000, 2)
            if response.status_code >= 400:
                try:
                    err = response.json()
                    message = err.get("error", err.get("message", str(err)))
                    if isinstance(message, dict):
                        message = message.get("message", str(message))
                except Exception:
                    message = response.text
                if isinstance(message, str):
                    message = message.encode("ascii", errors="replace").decode("ascii")
                logger.error(f"[PipedriveNode] API error ({action_name}): {message}")
                return {
                    "status": "error",
                    "action": action_name,
                    "error": message,
                    "status_code": response.status_code,
                    "timing_ms": {"api_request": api_ms},
                }
            if response.status_code == 204:
                data: Any = {"success": True}
            else:
                try:
                    payload = response.json()
                    # Pipedrive wraps results in {success, data, additional_data}
                    data = payload.get("data", payload) if isinstance(payload, dict) else payload
                except Exception:
                    data = {"raw": response.text}
            return {
                "status": "success",
                "action": action_name,
                "data": data,
                "status_code": response.status_code,
                "timing_ms": {"api_request": api_ms},
            }
        except httpx.TimeoutException:
            return {
                "status": "error",
                "action": action_name,
                "error": "Request timed out",
                "status_code": 408,
                "timing_ms": {"api_request": round((time.time() - start) * 1000, 2)},
            }
        except Exception as e:
            msg = str(e).encode("ascii", errors="replace").decode("ascii")
            logger.error(f"[PipedriveNode] Request failed ({action_name}): {msg}")
            return {
                "status": "error",
                "action": action_name,
                "error": msg,
                "status_code": 500,
                "timing_ms": {"api_request": round((time.time() - start) * 1000, 2)},
            }


def _resolve_request_auth(
    credential: Optional[Dict[str, Any]],
) -> Optional[Tuple[str, str, bool]]:
    """Resolve a (raw) credential dict to (base, token, auth_bearer).

    Works for both credential types: API-token creds carry ``company_domain`` +
    ``api_token``; OAuth creds carry ``access_token`` + ``api_domain`` (the
    company-specific base URL). Returns None when required fields are missing.
    """
    if not credential:
        return None
    access_token = credential.get("access_token")
    if access_token:  # OAuth credential
        base = credential.get("api_domain") or credential.get("company_domain")
        if not base:
            return None
        return base, access_token, True
    company_domain = credential.get("company_domain")
    api_token = credential.get("api_token")
    if not company_domain or not api_token:
        return None
    return company_domain, api_token, False


