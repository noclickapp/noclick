# Webhook event objects the trigger can subscribe to. This is the full set the
# Pipedrive Webhooks API accepts (live-verified) — deal/person/organization/
# activity/note/lead plus pipeline/product/stage/user.
WEBHOOK_EVENT_OBJECTS = [
    "deal", "person", "organization", "activity", "note", "lead",
    "pipeline", "product", "stage", "user",
]

# Webhook actions, in the v2 vocabulary Pipedrive uses for subscriptions.
WEBHOOK_EVENT_ACTIONS = ["create", "change", "delete"]

_OBJECT_LABELS = {
    "deal": "Deal",
    "person": "Person",
    "organization": "Organization",
    "activity": "Activity",
    "note": "Note",
    "lead": "Lead",
    "pipeline": "Pipeline",
    "product": "Product",
    "stage": "Stage",
    "user": "User",
}
_ACTION_LABELS = {"create": "created", "change": "changed", "delete": "deleted"}

# The webhook trigger is DECOMPOSED into one operation per (object, action) event
# — "On Deal Created", "On Person Updated", ... — so the AI builder (and users)
# pick a single concrete trigger node instead of one trigger multi-firing for a
# set of events. Each op maps to a fixed (event_object, event_action) Pipedrive
# subscription. A wildcard "On Any Pipedrive Event" covers fire-on-everything.
_TRIGGER_EVENTS: Dict[str, Tuple[str, str]] = {}   # op_name -> (event_object, event_action)
_TRIGGER_META: List[Tuple[str, str]] = []          # (op_name, display)
for _obj in WEBHOOK_EVENT_OBJECTS:
    for _action in WEBHOOK_EVENT_ACTIONS:
        _op_name = f"on_{_obj}_{_ACTION_LABELS[_action]}"          # on_deal_created
        _TRIGGER_EVENTS[_op_name] = (_obj, _action)
        _TRIGGER_META.append(
            (_op_name, f"On {_OBJECT_LABELS[_obj]} {_ACTION_LABELS[_action].capitalize()}")
        )
_TRIGGER_EVENTS["on_pipedrive_any_event"] = ("*", "*")
_TRIGGER_META.append(("on_pipedrive_any_event", "On Any Pipedrive Event"))

# Normalize the differing payload action vocabularies (v1 vs v2) to "create" /
# "change" / "delete" so the runtime filter compares apples to apples. Webhooks
# v2 already sends create/change/delete; v1 sends added/updated/deleted/merged.
_PAYLOAD_ACTION_ALIASES = {
    "create": "create",
    "added": "create",
    "add": "create",
    "change": "change",
    "updated": "change",
    "update": "change",
    "merged": "change",
    "delete": "delete",
    "deleted": "delete",
}


def _payload_event_type(payload: Dict[str, Any]) -> Tuple[Optional[str], Optional[str]]:
    """Extract (object, normalized_action) from an inbound Pipedrive webhook
    delivery, tolerating both v1 (``meta.object`` + ``added``/``updated``/...)
    and v2 (``meta.entity`` + ``create``/``change``/``delete``) payload shapes."""
    if not isinstance(payload, dict):
        return None, None
    meta = payload.get("meta") if isinstance(payload.get("meta"), dict) else {}
    obj = meta.get("entity") or meta.get("object")
    raw_action = meta.get("action")
    action = _PAYLOAD_ACTION_ALIASES.get(str(raw_action).lower()) if raw_action else None
    return (obj or None), action


