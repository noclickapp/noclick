def _titleize(name: str) -> str:
    return name.replace("_", " ").replace(".", " ").strip().title()


def _safe_attr(name: str) -> str:
    """A valid, non-reserved Python identifier for a raw API field/param name."""
    attr = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if not attr or attr[0].isdigit():
        attr = f"f_{attr}"
    if _keyword.iskeyword(attr):
        attr = f"{attr}_"
    return attr


def _dyn_extra(field_name: str) -> Optional[Dict[str, Any]]:
    """x-dynamic-options metadata the frontend DynamicOptionsField consumes. It
    MUST be an object carrying ``field_name`` (the value sent back to the backend
    loader) — a bare ``true`` drops field_name from the request and 422s."""
    if field_name not in _DYNAMIC_OPTION_FIELDS:
        return None
    opts: Dict[str, Any] = {
        "field_name": field_name,
        "searchable": True,
        "allow_custom": True,
        "placeholder": "Select or type…",
        "custom_placeholder": "Or paste an ID or reference",
    }
    if field_name == "stage_id":
        opts["depends_on"] = "pipeline_id"
    extra: Dict[str, Any] = {"x-dynamic-options": opts}
    rt = _FIELD_RESOURCE_TYPE.get(field_name)
    if rt:
        extra["x-resource-type"] = rt
    return extra


