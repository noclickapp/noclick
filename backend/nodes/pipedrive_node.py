def _extra_for(operation: str, name: str, ftype: str, desc: str) -> Optional[Dict[str, Any]]:
    """Per-field json_schema_extra including a static-enum dropdown when the field
    has a fixed value set (and isn't already a live-loaded dynamic dropdown)."""
    extra = dict(_field_extra(name, ftype, desc) or {})
    if "x-dynamic-options" not in extra:
        en = _field_enum(operation, name)
        if en:
            extra["enum"] = en
            extra["x-enum-searchable"] = True
    return extra or None


def _build_op(spec: Dict[str, Any]):
    """Return (config_model, runtime_spec) for one operation spec."""
    op = spec["operation"]
    display = spec["display"]
    category = spec["category"]

    fields: Dict[str, Any] = {
        "operation": (
            Literal[op],
            Field(
                op,
                title=display,
                json_schema_extra={
                    "const": op,
                    "ui:hidden": True,
                    "x-category": category,
                    "x-is-trigger": False,
                    "x-display-name": display,
                    **(
                        {
                            "x-creates-resource": True,
                            "x-resource-type": _CREATES_RESOURCE[op][0],
                            "x-resource-id-path": _CREATES_RESOURCE[op][1],
                        }
                        if op in _CREATES_RESOURCE
                        else {}
                    ),
                },
            ),
        )
    }
    seen = {"operation"}
    rt_path_params: List[tuple] = []
    rt_query: List[tuple] = []  # (attr, api_name)
    rt_body: List[tuple] = []   # (attr, api_name, json_type)

    for p in spec.get("path_params", []):
        attr = _safe_attr(p)
        if attr in seen:
            continue
        seen.add(attr)
        fields[attr] = (
            str,
            Field(..., title=_titleize(p),
                  description=f"{_titleize(p)} (path parameter)",
                  json_schema_extra=_extra_for(op, p, "string", "")),
        )
        rt_path_params.append((attr, p))

    for bf in spec.get("body", []):
        api, required, ftype, desc = bf
        attr = _safe_attr(api)
        if attr in seen:
            continue
        seen.add(attr)
        if required:
            fields[attr] = (str, Field(..., title=_titleize(api), description=desc,
                                       json_schema_extra=_extra_for(op, api, ftype, desc)))
        else:
            fields[attr] = (Optional[str], Field(None, title=_titleize(api), description=desc,
                                                 json_schema_extra=_extra_for(op, api, ftype, desc)))
        rt_body.append((attr, api, ftype))

    for q in spec.get("query", []):
        attr = _safe_attr(q)
        if attr in seen:
            continue
        seen.add(attr)
        extra = _extra_for(op, q, "string", "")
        if (op, q) in _REQUIRED_QUERY:
            fields[attr] = (str, Field(..., title=_titleize(q),
                                       description=_query_desc(q), json_schema_extra=extra))
        else:
            fields[attr] = (Optional[str], Field(None, title=_titleize(q),
                                                 description=_query_desc(q), json_schema_extra=extra))
        rt_query.append((attr, q))

    model = create_model(f"Pipedrive_{op}_Config", **fields)
    runtime = {
        "version": spec.get("version", "v2"),
        "method": spec["method"],
        "path": spec["path"],
        "path_params": rt_path_params,
        "query": rt_query,
        "body": rt_body,
    }
    return model, runtime


_OP_MODELS: Dict[str, Any] = {}
_OP_RUNTIME: Dict[str, Dict[str, Any]] = {}
for _spec in OP_SPECS:
    _op_name = _spec["operation"]
    if _op_name in _OP_MODELS:
        raise ValueError(f"Duplicate Pipedrive operation in registry: {_op_name}")
    _model, _runtime = _build_op(_spec)
    _OP_MODELS[_op_name] = _model
    _OP_RUNTIME[_op_name] = _runtime


