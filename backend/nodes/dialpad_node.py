class DialpadOperation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="after")
    def validate_arguments(self):
        values = self.model_dump(exclude_none=True)
        if values.get("target_id") is not None and not values.get("target_type"):
            raise ValueError("Target type is required with target ID")
        if values.get("operation") == "send_sms":
            if not values.get("from_number") and values.get("user_id") is None:
                raise ValueError("Provide a sender phone number or user ID")
            numbers = _comma_list(values["to_numbers"])
            if not 1 <= len(numbers) <= 10:
                raise ValueError("Provide between 1 and 10 recipient phone numbers")
        if values.get("operation") in ("update_contact", "update_user"):
            if not any(k not in ("operation", "id") for k in values):
                raise ValueError("Provide at least one field to update")
        if values.get("operation") == "list_users":
            if (values.get("first_name") or values.get("last_name")) and (values.get("email") or values.get("number")):
                raise ValueError("Name filters cannot be combined with email or phone number")
        return self


def _comma_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


