# One-to-one mappings to operations in the pinned provider OpenAPI.
ROUTES = {
    'list_calls': ('GET', '/api/v2/call'),
    'get_call': ('GET', '/api/v2/call/{id}'),
    'initiate_call': ('POST', '/api/v2/call'),
    'transfer_call': ('POST', '/api/v2/call/{id}/transfer'),
    'hangup_call': ('PUT', '/api/v2/call/{id}/actions/hangup'),
    'add_call_labels': ('PUT', '/api/v2/call/{id}/labels'),
    'send_sms': ('POST', '/api/v2/sms'),
    'list_contacts': ('GET', '/api/v2/contacts'),
    'get_contact': ('GET', '/api/v2/contacts/{id}'),
    'create_contact': ('POST', '/api/v2/contacts'),
    'update_contact': ('PATCH', '/api/v2/contacts/{id}'),
    'delete_contact': ('DELETE', '/api/v2/contacts/{id}'),
    'list_users': ('GET', '/api/v2/users'),
    'get_user': ('GET', '/api/v2/users/{id}'),
    'update_user': ('PATCH', '/api/v2/users/{id}'),
    'set_user_dnd': ('PATCH', '/api/v2/users/{id}/togglednd'),
    'get_company': ('GET', '/api/v2/company'),
}

ARRAY_FIELDS = {
    'add_call_labels': ['labels'],
    'send_sms': ['to_numbers'],
    'create_contact': ['emails', 'phones', 'urls'],
    'update_contact': ['emails', 'phones', 'urls'],
    'update_user': ['emails'],
}

class DialpadNode(WorkflowNode):
    integration_type = "automation-dialpad"

    @classmethod
    def get_config_model(cls):
        return DialpadNodeConfig

    connection_evidence = ConnectionEvidence(
        operation="list_users", noun="users", identity_operation="get_company",
    )

    async def execute(self, inputs: Dict[str, Any]) -> Dict[str, Any]:
        started = time.perf_counter()
        if not isinstance(self.config, DialpadNodeConfig):
            raise ValueError("Valid Dialpad configuration is required")
        if not self.config.credentials:
            raise ValueError("Dialpad API key is required")
        op = self.config.config
        action = op.operation
        method, path = ROUTES[action]
        values = op.model_dump(exclude_none=True, exclude={"operation"})
        if "{id}" in path:
            path = path.replace("{id}", quote(str(values.pop("id")), safe=""))
        for key in ARRAY_FIELDS.get(action, ()):
            if key in values:
                values[key] = _comma_list(values[key])
        if action == "transfer_call":
            values["to"] = {"number": values.pop("to_number")}
        kwargs = {"params": values} if method == "GET" else ({"json": values} if values else {})
        api_started = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.request(method, API_BASE + path, headers={
                    "Authorization": f"Bearer {self.config.credentials.api_key}",
                    "Accept": "application/json",
                }, **kwargs)
            timing = {"api_request": round((time.perf_counter() - api_started) * 1000, 2),
                      "total": round((time.perf_counter() - started) * 1000, 2)}
            base = {"action": action, "status_code": response.status_code, "timing_ms": timing}
            if not response.is_success:
                # Preserve the provider's rejection text for credential connect.
                return {**base, "status": "error", "error": response.text}
            data = response.json() if response.content else {}
            if not isinstance(data, dict):
                return {**base, "status": "error", "error": "Dialpad returned an invalid JSON object"}
            if data.get("error") or data.get("errors") or data.get("success") is False or data.get("status") in ("error", "failed"):
                return {**base, "status": "error", "error": str(data.get("error") or data.get("errors") or data)}
            if action in ("list_users", "list_contacts", "list_calls"):
                if "items" not in data or (data["items"] is not None and (
                    not isinstance(data["items"], list) or any(not isinstance(row, dict) for row in data["items"])
                )):
                    return {**base, "status": "error", "error": "Dialpad returned an invalid collection"}
            if action == "get_company" and not (data.get("id") and data.get("name")):
                return {**base, "status": "error", "error": "Dialpad returned an invalid company identity"}
            return {**base, "status": "success", "data": data}
        except (httpx.HTTPError, ValueError) as exc:
            return {"status": "error", "action": action, "error": str(exc), "timing_ms": {
                "api_request": round((time.perf_counter() - api_started) * 1000, 2),
                "total": round((time.perf_counter() - started) * 1000, 2),
            }}
